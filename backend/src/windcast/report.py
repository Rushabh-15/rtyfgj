"""Write ``docs/analysis.md`` from the derived tables, so every number in the report is regenerated from data.

``windcast report`` is deterministic; CI regenerates the file and fails if the committed copy differs.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from windcast import study
from windcast.study import cutoff_key


def _load(path: Path) -> Any:
    return json.loads(path.read_text())


def _mw(x: float | None) -> str:
    return "–" if x is None else f"{x:,.0f}"


def _signed(x: float) -> str:
    return f"{x:+,.0f}"


def _pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}%"


def _stats_row(label: str, s: dict[str, Any] | None) -> str:
    if s is None:
        return f"| {label} | 0 | – | – | – | – | – | – |"
    return (
        f"| {label} | {s['n']:,} | {_signed(s['mean_error_mw'])} | {_mw(s['mae_mw'])} | {_mw(s['rmse_mw'])} | "
        f"{_signed(s['p10_mw'])} | {_signed(s['p50_mw'])} | {_signed(s['p90_mw'])} |"
    )


STATS_HEADER = (
    "| {first} | Half-hours | Mean error | MAE | RMSE | P10 | P50 | P90 |\n"
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"
)


def build_report(derived: Path) -> str:
    meta = _load(derived / "meta.json")
    base = derived / "alignment_0"
    shifted = derived / "alignment_-30"
    default = _load(base / "cutoffs" / f"{cutoff_key(study.CUTOFF_DEFAULT)}.json")
    default_shifted = _load(shifted / "cutoffs" / f"{cutoff_key(study.CUTOFF_DEFAULT)}.json")
    vintages = _load(base / "vintages.json")
    acc = default["accuracy"]
    f = acc["forecast"]
    b = {row["target_pct"]: row for row in acc["buffer"]}[study.DEFAULT_COVERAGE]
    level = acc["by_level"]
    top, bottom = level[-1]["stats"], level[0]["stats"]
    days = default["days"]
    worst = sorted(days, key=lambda d: -d["stats"]["mae_mw"])[:3]
    hours = [row for row in vintages["by_hour_uk"] if row["stats"]]
    night = max(hours, key=lambda r: r["stats"]["mean_error_mw"])
    afternoon = min(hours, key=lambda r: r["stats"]["mean_error_mw"])
    lag = acc["lag_scan"]
    lag0 = next(p for p in lag if p["shift_minutes"] == 0)
    best_sd = min(lag, key=lambda p: p["sd_mw"])
    best_mae = min(lag, key=lambda p: p["mae_mw"])
    short = vintages["short_lead_lag_scan"]
    short0 = next(p for p in short if p["shift_minutes"] == 0)
    short_best = min(short, key=lambda p: p["sd_mw"])
    s_mae = default_shifted["accuracy"]["forecast"]["mae_mw"]
    cutoff = meta["default_cutoff_uk"]

    out: list[str] = []
    w = out.append
    w("# Accuracy analysis: WINDFOR at the decision cutoff vs FUELHH outturn")
    w("")
    w(
        f"_Generated by `windcast report` from `data/derived` (snapshot SHA-256 "
        f"{meta['snapshot'][0]['sha256'][:12]}…, {meta['snapshot'][1]['sha256'][:12]}…). Delivery days "
        f"{meta['delivery_days'][0]} to {meta['delivery_days'][-1]} (decisions 1–31 January 2026), 23:00–23:00 UK, "
        f"{default['periods']:,} half-hours. Errors are forecast minus outturn in MW: positive means wind came in "
        "below forecast, i.e. a shortfall the desk has to cover._"
    )
    w("")
    w("## Headline")
    w("")
    w(
        f"At the default cutoff ({cutoff} UK on D−1, which selects the {default['runs_used_utc'][0][11:16]} UTC run "
        f"every day, {default['lead_hours'][0]:g}–{default['lead_hours'][1]:g} h ahead), the forecast ran "
        f"**{f['mean_error_mw']:,.0f} MW above outturn on average** (MAE {f['mae_mw']:,.0f} MW, RMSE "
        f"{f['rmse_mw']:,.0f} MW). Wind fell short of the forecast in {_pct(f['shortfall_share'], 0)} of half-hours; "
        f"the median shortfall was {f['p50_mw']:,.0f} MW and the P10–P90 range {f['p10_mw']:,.0f} to "
        f"{f['p90_mw']:,.0f} MW ({f['p90_mw'] - f['p10_mw']:,.0f} MW wide)."
    )
    w("")
    w(
        f"**Buffer.** Buying **{b['buffer_mw']:,.0f} MW** beyond the forecast-implied volume covered wind shortfalls in "
        f"{study.DEFAULT_COVERAGE}% of half-hours on the fit days ({meta['fit_days'][0]} to {meta['fit_days'][1]}). "
        f"Applied unchanged to {meta['test_days'][0]} to {meta['test_days'][1]}, it covered "
        f"**{_pct(b['test_coverage'])}** of half-hours (95% day-block bootstrap interval {_pct(b['test_coverage_low'])}"
        f"–{_pct(b['test_coverage_high'])}). Refitted on all 31 days it would be {b['full_month_buffer_mw']:,.0f} MW."
    )
    w("")
    w(
        f"**Skill.** The forecast's MAE is {_pct(acc['skill_mae'], 0)} lower than persistence (the last outturn "
        f"published before the cutoff, held for the day: MAE {acc['persistence']['mae_mw']:,.0f} MW)."
    )
    w("")
    w(
        f"**Where the error comes from.** The gap grows with the forecast level: {_signed(bottom['mean_error_mw'])} MW "
        f"when the forecast is under 6 GW, {_signed(top['mean_error_mw'])} MW when it is 18 GW or more, where wind "
        f"fell short in {_pct(top['shortfall_share'], 0)} of half-hours. Across all forecast runs it is largest at "
        f"night ({night['label']} UK: {_signed(night['stats']['mean_error_mw'])} MW) and smallest mid-afternoon "
        f"({afternoon['label']}: {_signed(afternoon['stats']['mean_error_mw'])} MW). Both patterns are consistent with "
        "curtailment of wind at high output and low demand (unverified: the balancing data needed to confirm it is "
        "outside the brief)."
    )
    w("")
    w("## Accuracy by cutoff")
    w("")
    w(
        "Later cutoffs use later runs. The rule is the latest run published strictly before the cutoff, so on "
        "15 January (11:30 run missing, 12:25 run late) cutoffs from 12:00 fall back to the 09:30 run until 12:25."
    )
    w("")
    w(
        "| Cutoff (UK, D−1) | Runs used (UTC) | Lead (h) | Mean error | MAE | P90 | 90% buffer | Test coverage | Skill vs persistence |"
    )
    w("| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for t in study.cutoff_grid():
        c = _load(base / "cutoffs" / f"{cutoff_key(t)}.json")
        a = c["accuracy"]
        b90 = {row["target_pct"]: row for row in a["buffer"]}[90]
        runs = ", ".join(sorted({r[11:16] for r in c["runs_used_utc"]}))
        w(
            f"| {c['cutoff_uk']} | {runs} | {c['lead_hours'][0]:g}–{c['lead_hours'][1]:g} | "
            f"{_signed(a['forecast']['mean_error_mw'])} | {_mw(a['forecast']['mae_mw'])} | "
            f"{_signed(a['forecast']['p90_mw'])} | {_mw(b90['buffer_mw'])} | {_pct(b90['test_coverage'])} | "
            f"{_pct(a['skill_mae'], 0)} |"
        )
    w("")
    w(f"## Error by lead time ({cutoff} cutoff)")
    w("")
    w(STATS_HEADER.format(first="Lead time"))
    for row in acc["by_lead"]:
        w(_stats_row(row["label"], row["stats"]))
    w("")
    w(
        "With one cutoff per day, lead time and time of day move together (15.5 h ahead is always 23:00 UK), so this "
        "table mixes the two. The all-vintage view below separates them."
    )
    w("")
    w(f"## Error by forecast level ({cutoff} cutoff)")
    w("")
    w(STATS_HEADER.format(first="Forecast level"))
    for row in level:
        w(_stats_row(row["label"], row["stats"]))
    w("")
    w(
        "Conditioning on the forecast (not the outturn) keeps this usable at decision time: the P90 column is the "
        "buffer a desk would hold for each forecast band."
    )
    w("")
    w("## All forecast vintages: lead time vs hour of day")
    w("")
    w(
        f"Every forward-looking (run, half-hour) pair for the delivery window: {vintages['pairs']:,} pairs from "
        f"{vintages['runs']} runs. On a grid of 6-hour lead buckets by UK hour (complete buckets only, so each factor "
        f"is averaged over the other), MAE varies by **{vintages['lead_effect_mw']:,.0f} MW across lead buckets** and "
        f"**{vintages['hour_effect_mw']:,.0f} MW across hours of day** (leads {vintages['effect_leads_h'][0]}–"
        f"{vintages['effect_leads_h'][1]} h): when the period falls matters more than how far ahead it was forecast."
    )
    w("")
    w(STATS_HEADER.format(first="Lead time"))
    for row in vintages["by_lead"]:
        w(_stats_row(row["label"], row["stats"]))
    w("")
    lo, hi = vintages["by_hour_lead_range_h"]
    w(f"By UK hour of the period start, leads {lo}–{hi} h:")
    w("")
    w(STATS_HEADER.format(first="Hour (UK)"))
    for row in vintages["by_hour_uk"]:
        w(_stats_row(row["label"], row["stats"]))
    w("")
    w(f"## Persistence baseline ({cutoff} cutoff)")
    w("")
    w(STATS_HEADER.format(first="Forecast"))
    w(_stats_row("WINDFOR at cutoff", acc["forecast"]))
    w(_stats_row("Persistence", acc["persistence"]))
    w("")
    w(
        f"Skill: {_pct(acc['skill_mae'])} on MAE, {_pct(acc['skill_rmse'])} on RMSE. Persistence is a low bar 15–39 "
        "hours ahead; beating it shows the forecast carries information, not that it is unbiased."
    )
    w("")
    w(f"## Buffer back-test ({cutoff} cutoff)")
    w("")
    w(
        "Buffer = the target quantile of shortfall (forecast − outturn) over the fit days' half-hours. Coverage = share "
        "of half-hours with shortfall ≤ buffer. The interval resamples whole test days 5,000 times, because half-hours "
        "within a day are strongly correlated."
    )
    w("")
    w(
        "| Target | Buffer (MW, fitted 2–16 Jan) | Fit coverage | Test coverage (17 Jan–1 Feb) | 95% interval | Refit on all days (MW) |"
    )
    w("| ---: | ---: | ---: | ---: | --- | ---: |")
    for row in acc["buffer"]:
        w(
            f"| {row['target_pct']}% | {row['buffer_mw']:,.0f} | {_pct(row['fit_coverage'])} | "
            f"{_pct(row['test_coverage'])} | {_pct(row['test_coverage_low'])}–{_pct(row['test_coverage_high'])} | "
            f"{row['full_month_buffer_mw']:,.0f} |"
        )
    w("")
    fifty = {row["target_pct"]: row for row in acc["buffer"]}[50]
    w(
        f"The upper targets held out of sample; the 50% buffer did not ({_pct(fifty['test_coverage'])}), because the "
        "systematic gap was larger in the windier second half of January. A median-level buffer is a bet on the bias "
        "staying put; the upper quantiles absorb it."
    )
    w("")
    w("## Worst days")
    w("")
    w("| Delivery day | MAE | Mean error |")
    w("| --- | ---: | ---: |")
    for d in worst:
        w(f"| {d['delivery_day']} | {d['stats']['mae_mw']:,.0f} | {_signed(d['stats']['mean_error_mw'])} |")
    w("")
    w(
        "NESO's [January 2026 incentive report](https://www.neso.energy/document/377601/download) attributes its "
        "large error on 28 January to an IT issue that stopped updated weather forecasts being processed on "
        "27 January, and notes storms (Goretti, Ingrid, Chandra) with high-speed turbine shutdowns during the month."
    )
    w("")
    w("## Timing check: lag scan")
    w("")
    w(
        "Forecast for period t compared with outturn at t + shift, for the same 1,488 periods at every shift. "
        '"SD" is the error spread with the mean removed, which is not distorted by the level of the bias.'
    )
    w("")
    w("| Shift (min) | Mean error | MAE | RMSE | SD | Correlation | Short-lead SD (<6 h, all runs) |")
    w("| ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for p, q in zip(lag, short, strict=True):
        w(
            f"| {p['shift_minutes']:+d} | {_signed(p['mean_error_mw'])} | {_mw(p['mae_mw'])} | {_mw(p['rmse_mw'])} | "
            f"{_mw(p['sd_mw'])} | {p['correlation']:.4f} | {_mw(q['sd_mw'])} |"
        )
    w("")
    w(
        f"The minimum is not at zero: MAE is lowest at {best_mae['shift_minutes']:+d} min and the bias-removed spread "
        f"at {best_sd['shift_minutes']:+d} min ({best_sd['sd_mw']:,.0f} vs {lag0['sd_mw']:,.0f} MW at zero, "
        f"{(lag0['sd_mw'] - best_sd['sd_mw']) / lag0['sd_mw']:.1%} lower). Short-lead runs put it at "
        f"{short_best['shift_minutes']:+d} min ({(short0['sd_mw'] - short_best['sd_mw']) / short0['sd_mw']:.1%} lower). "
        "That fits WINDFOR values describing the hour ending at, or the instant of, their label rather than the hour "
        "starting at it, or forecast ramps arriving early. Elexon's own forecast endpoints label the value at "
        "startTime H with the settlement period starting at H, and the default alignment follows them; the shifted "
        f"alignment (`WINDCAST_ALIGNMENT_SHIFT_MINUTES=-30`) lowers MAE from {f['mae_mw']:,.0f} to {s_mae:,.0f} MW "
        f"({(f['mae_mw'] - s_mae) / f['mae_mw']:.1%})."
    )
    w("")
    w("## Limitations")
    w("")
    w(
        "- **Curtailment.** FUELHH is metered output after any curtailment. The gap grows with forecast level and at "
        "night, consistent with curtailment (unverified). If it is curtailment, the buffer may overstate the desk's "
        "need at high wind."
    )
    w(
        "- **Embedded wind.** Both datasets cover wind farms with operational metering visible to NESO; smaller "
        "distribution-connected wind is in neither and shows up as lower demand, not as wind."
    )
    w(
        "- **Coverage differences.** WINDFOR ran above NESO's own day-ahead incentive forecast for BM wind units in "
        "January (see the NESO check in `docs/validation.md`), so part of the gap may be fleet coverage or model "
        "differences rather than weather error."
    )
    w(
        "- **Sample.** One winter month: 15 fit days and 16 test days. Errors are correlated within a day, so the "
        "effective sample is closer to 31 days than 1,488 half-hours, and the coverage intervals are wide."
    )
    w(
        "- **Resolution.** WINDFOR is hourly; each value is applied to two half-hours. The lag scan suggests the "
        "values fit outturn 30–60 minutes earlier than their label."
    )
    w("")
    return "\n".join(out)


def write_report(derived: Path, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_report(derived))
